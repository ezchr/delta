// Command genvanilla writes vanilla_gen.go: the names of the vanilla Bedrock resource pack's
// block and item textures and its terrain/item texture keys (names and paths only, no content),
// from a vanilla resource pack folder such as Mojang's bedrock-samples resource_pack.
//
//	go run ./tools/genvanilla -rp <bedrock-samples>/resource_pack > vanilla_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"javabridge/packconv"
)

func main() {
	rp := flag.String("rp", "", "vanilla Bedrock resource pack folder")
	list := flag.String("list", "", "file listing texture paths (instead of walking -rp/textures)")
	flag.Parse()
	var paths []string
	if *list != "" {
		b, err := os.ReadFile(*list)
		if err != nil {
			panic(err)
		}
		paths = strings.Fields(string(b))
	} else {
		for _, d := range []string{"textures/blocks", "textures/items"} {
			_ = filepath.WalkDir(filepath.Join(*rp, d), func(p string, e fs.DirEntry, err error) error {
				if err == nil && !e.IsDir() {
					rel, _ := filepath.Rel(*rp, p)
					paths = append(paths, filepath.ToSlash(rel))
				}
				return nil
			})
		}
	}
	pbr := regexp.MustCompile(`_(mers|mer|normal|heightmap)$`)
	set := map[string]bool{}
	for _, p := range paths {
		ext := filepath.Ext(p)
		if ext != ".png" && ext != ".tga" {
			continue
		}
		p = strings.ToLower(strings.TrimSuffix(p, ext))
		if pbr.MatchString(p) {
			continue
		}
		set[p] = true
	}
	var w bytes.Buffer
	fmt.Fprintln(&w, "// Code generated by tools/genvanilla from the vanilla Bedrock resource pack (names only); DO NOT EDIT.")
	fmt.Fprintln(&w, "\npackage packconv\n\n// bedrockVanillaTextures are the vanilla Bedrock block and item texture paths (no extension).")
	fmt.Fprint(&w, "const bedrockVanillaTextures = `\n")
	writeWrapped(&w, sorted(set))
	fmt.Fprint(&w, "`\n")
	for _, t := range []struct{ file, name, doc string }{
		{"textures/terrain_texture.json", "bedrockTerrainKeys", "vanilla terrain_texture.json keys and their first texture path"},
		{"textures/item_texture.json", "bedrockItemKeys", "vanilla item_texture.json keys and their first texture path"},
	} {
		b, err := os.ReadFile(filepath.Join(*rp, t.file))
		if err != nil {
			panic(err)
		}
		var f struct {
			TextureData map[string]struct {
				Textures json.RawMessage `json:"textures"`
			} `json:"texture_data"`
		}
		if err := json.Unmarshal(packconv.CleanJSON(b), &f); err != nil {
			panic(err)
		}
		var lines []string
		for k, v := range f.TextureData {
			if p := first(v.Textures); p != "" {
				lines = append(lines, k+"="+strings.ToLower(p))
			}
		}
		sort.Strings(lines)
		fmt.Fprintf(&w, "\n// %s are the %s.\nconst %s = `\n", t.name, t.doc, t.name)
		writeWrapped(&w, lines)
		fmt.Fprint(&w, "`\n")
	}
	os.Stdout.Write(w.Bytes())
}

func writeWrapped(w *bytes.Buffer, items []string) {
	line := 0
	for _, s := range items {
		if line > 0 && line+len(s)+1 > 100 {
			w.WriteByte('\n')
			line = 0
		}
		if line > 0 {
			w.WriteByte(' ')
			line++
		}
		w.WriteString(s)
		line += len(s)
	}
	w.WriteByte('\n')
}

func sorted(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func first(raw json.RawMessage) string {
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return s
	}
	var list []json.RawMessage
	if json.Unmarshal(raw, &list) == nil {
		for _, e := range list {
			if p := first(e); p != "" {
				return p
			}
		}
		return ""
	}
	var obj struct {
		Path string `json:"path"`
	}
	if json.Unmarshal(raw, &obj) == nil {
		return obj.Path
	}
	return ""
}
