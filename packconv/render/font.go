package render

import (
	"image"
	"image/color"
	"strings"
)

// A 3x5 pixel font for sheet labels (lower case letters, digits and a few signs).
var glyphs = map[rune]string{
	'a': "010101111101101", 'b': "110101110101110", 'c': "011100100100011", 'd': "110101101101110",
	'e': "111100110100111", 'f': "111100110100100", 'g': "011100101101011", 'h': "101101111101101",
	'i': "111010010010111", 'j': "001001001101010", 'k': "101101110101101", 'l': "100100100100111",
	'm': "101111111101101", 'n': "110101101101101", 'o': "010101101101010", 'p': "110101110100100",
	'q': "010101101110011", 'r': "110101110101101", 's': "011100010001110", 't': "111010010010010",
	'u': "101101101101111", 'v': "101101101101010", 'w': "101101111111101", 'x': "101101010101101",
	'y': "101101010010010", 'z': "111001010100111", '0': "111101101101111", '1': "010110010010111",
	'2': "110001010100111", '3': "110001010001110", '4': "101101111001001", '5': "111100110001110",
	'6': "011100111101111", '7': "111001010010010", '8': "111101111101111", '9': "111101111001110",
	':': "000010000010000", '_': "000000000000111", '.': "000000000000010", '/': "001001010100100",
	'-': "000000111000000", ' ': "000000000000000", '(': "010100100100010", ')': "010001001001010",
	'=': "000111000111000", ',': "000000000010100", '+': "000010111010000",
}

// Label draws text at (x, y) with pixels of size scale.
func Label(img *image.NRGBA, x, y, scale int, text string, col color.NRGBA) {
	for _, r := range strings.ToLower(text) {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs['-']
		}
		for i, c := range g {
			if c != '1' {
				continue
			}
			gx, gy := i%3, i/3
			for dy := 0; dy < scale; dy++ {
				for dx := 0; dx < scale; dx++ {
					p := image.Pt(x+gx*scale+dx, y+gy*scale+dy)
					if p.In(img.Bounds()) {
						img.SetNRGBA(p.X, p.Y, col)
					}
				}
			}
		}
		x += 4 * scale
	}
}
